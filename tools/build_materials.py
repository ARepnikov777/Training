def main():
    assets = ROOT / "build-cache"
    assets.mkdir(exist_ok=True)
    document_sets.prepare_assets(assets)
    root = ROOT / "materials"
    programming(root, assets)
    datasets.make(root)
    document_sets.make(root, assets)
    visual_sets.make(root, assets)
    browser_sets.make(root)
    issues = json.loads((ROOT / "tools/issue-source.json").read_text())
    catalog = []
    for issue in issues:
        code = issue["code"]
        p = root / code
        inputs = sorted(
            str(f.relative_to(p))
            for f in (p / "input").rglob("*")
            if f.is_file()
            and f.name != "_state.json"
            and "__pycache__" not in f.parts
            and f.name != "_state.json"
            and "__pycache__" not in f.parts
        )
        checks = sorted(
            str(f.relative_to(p))
            for f in (p / "checks").rglob("*")
            if f.is_file() and f.name != "_state.json" and "__pycache__" not in f.parts
        )
        assert inputs and checks, code
        rows = "\n".join("- `" + x + "`" for x in inputs)
        references = "\n".join("- `" + x + "`" for x in checks)
        start = "Распакуй ZIP в отдельную папку. Прочитай все файлы .md/.json в input: они задают точные правила, ограничения и входные значения. Работай в отдельной рабочей папке, результат сохрани в result. Контрольные файлы checks можно использовать для самопроверки: это эталоны данных, не готовое решение. CSV: UTF-8, разделитель запятая, десятичная точка; в Excel используйте импорт «Из текста/CSV» с этими параметрами."
        if (p / "input/site/serve.py").exists():
            start += "\n\nЗапуск локального стенда из папки задания: `python input/site/serve.py --port 8765`. На Linux/macOS можно `python3`, на Windows — `py -3`. Открой `http://127.0.0.1:8765/`. При занятом порте замени 8765 на 8766 в команде и адресе. Дополнительных пакетов не нужно. Детали — input/START.md."
        if code in ["E02", "M02", "H02"]:
            start += "\n\nПерейди в копию input/project и выполни `python -m unittest discover -v`: существующие тесты проходят, но не покрывают выданные дефекты. Добавь новые тесты по SPEC.md и checks. Для H02 инициализируй учебный Git-репозиторий по SPEC.md."
        if code in ["M06", "H06"]:
            start += "\n\nЗапись синтезирована офлайн на русском языке. Длительность — input/audio-info.json. Открой meeting.mp3 в любом аудиоплеере. Для распознавания используй доступный инструмент; при его отсутствии сначала составь протокол по прослушиванию, затем сверяй с checks/transcript.md. Не выдавай эталон за собственное распознавание."
        if code in ["E10", "E12", "M10", "H10"]:
            start += "\n\nЕсли AI-генератор недоступен, собери собственные SVG-композиции из вложенных элементов. Для экспорта PNG открой input/rasterize.html в браузере и выбери свой SVG с заданными width/height."
        if code in ["H02", "H09", "H12"]:
            start += "\n\nНезависимая работа означает отдельного слушателя или отдельный процесс/сессию агента с ограниченным поручением; не имитируй её вторым ответом того же диалога. Субагенты либо второй локальный процесс доступны через используемый на курсе харнес; платная отдельная API-подписка не требуется."
        readme = f"# {issue['title']}\n\n## Что сделать\n\n{GOALS[code]}\n\n## Как начать\n\n{start}\n\n## Входные файлы\n\n{rows}\n\n## Самопроверка\n\n{references}\n\n## Что сдать\n\nГотовый результат, исходники/промпты при наличии, инструкцию открытия/запуска и краткие доказательства проверки. Для программных дефектов — падение регрессионного теста до исправления и прохождение после. Для документов/графики — визуальная проверка. Готовые решения заданий не включены.\n\n## Ограничения\n\nДанные специально созданы для курса; это не реальные персональные, финансовые или коммерческие сведения. Все исходники доступны в этом комплекте; искать дополнительные материалы у преподавателя не нужно. Работа только на своём компьютере, без SSH, удалённых серверов и облачного развёртывания. Не перезаписывай выданные исходники.\n"
        text(p / "README.md", readme)
        jsn(
            p / "manifest.json",
            {
                "code": code,
                "issue": issue["number"],
                "title": issue["title"],
                "goal": GOALS[code],
                "inputs": inputs,
                "checks": checks,
            },
        )
        files = {
            str(f.relative_to(p)): f.read_bytes()
            for f in p.rglob("*")
            if f.is_file()
            and "__pycache__" not in f.parts
            and f.name not in {"_state.json", "checksums.json"}
        }
        checksums = {
            name: hashlib.sha256(value).hexdigest()
            for name, value in sorted(files.items())
        }
        jsn(p / "checksums.json", checksums)
        files["checksums.json"] = (p / "checksums.json").read_bytes()
        archive(
            ROOT / "downloads" / f"{code}.zip",
            {code + "/" + name: content for name, content in files.items()},
        )
        catalog.append(
            {
                "code": code,
                "issue": issue["number"],
                "goal": GOALS[code],
                "path": "materials/" + code,
                "zip": "downloads/" + code + ".zip",
                "sha256": hashlib.sha256(
                    (ROOT / "downloads" / f"{code}.zip").read_bytes()
                ).hexdigest(),
                "file_count": len(files),
            }
        )
    assert len(catalog) == 45
    jsn(ROOT / "catalog.json", catalog)
    text(
        ROOT / "README.md",
        "# Материалы курса по агентной разработке\n\n45 самостоятельных учебных комплектов. Все документы, люди, товары и числа синтетические. Никакие материалы от преподавателя дополнительно не требуются.\n\nДля выполнения задания откройте его issue, скачайте ZIP по ссылке «Скачать комплект», распакуйте и прочитайте README внутри. Браузерные стенды работают локально на Python 3.10+ без дополнительных пакетов. Для создания изображений дан вариант без платного генератора. Эталонные данные находятся в checks; алгоритмы решений не выданы.\n\n|Код|Задание|Материалы|Скачать|\n|---|---|---|---|\n"
        + "\n".join(
            f"|{x['code']}|[#{x['issue']}](https://github.com/ARepnikov777/Training/issues/{x['issue']})|[{x['path']}]({x['path']})|[ZIP]({x['zip']})|"
            for x in catalog
        )
        + "\n\n## Пересборка для организатора\n\nPython 3.14, зависимости из requirements-build.txt, шрифт DejaVu Sans и libespeak-ng с русским голосом, ffmpeg. Команда: `python tools/build_materials.py`. Для слушателя пересборка не нужна: готовые PDF, PNG и MP3 включены. Проверка: `python -m pytest tests -q`, `ruff check tools tests`, `ruff format --check tools tests`. Намеренно неисправный код лежит только в учебных input/project и стендах mode=*-buggy; проверки самого комплекта должны проходить.\n\n## Лицензии\n\nКод — MIT, собственные учебные тексты и данные/иллюстрации — CC0 1.0; см. LICENSE. Внешние фотографии или персональные документы не использованы.\n",
    )
    print(f"Созданы {len(catalog)} комплектов и ZIP", flush=True)


if __name__ == "__main__":
    main()
