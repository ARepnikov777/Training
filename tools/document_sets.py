def prepare_assets(assets):
    pdf(assets / "text.pdf", [SCAN_PAGES[0]])
    pdf(assets / "scan.pdf", SCAN_PAGES, scan=True)
    table_pdf(assets / "table-scan.pdf")
    pdf(assets / "sop.pdf", SOP)
    from documents import product_images

    product_images(assets / "images")
    script_path = Path(__file__).parent / "meeting-script.json"
    script_path.write_text(json.dumps(MEETING, ensure_ascii=False, indent=2))
    if not (assets / "audio/meeting.wav").exists():
        duration = synthesize_meeting(assets / "audio")
        print(f"Синтетическое аудио: {duration:.1f} секунд", flush=True)
    if not (assets / "audio/meeting.mp3").exists():
        import subprocess

        subprocess.run(
            [
                "ffmpeg",
                "-hide_banner",
                "-loglevel",
                "error",
                "-y",
                "-i",
                str(assets / "audio/meeting.wav"),
                "-ac",
                "1",
                "-b:a",
                "48k",
                str(assets / "audio/meeting.mp3"),
            ],
            check=True,
        )


